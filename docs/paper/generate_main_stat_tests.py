#!/usr/bin/env python3
"""Generate paired statistical tests for TA-BRPL main experiment outputs.

Inputs (from generate_main_experiment_artifacts.py output):
  - paired_deltas_by_topology.csv

Outputs:
  - stat_tests_by_scope_metric.csv
  - pdr_noninferiority_tests.csv
  - table_main_v2_paired_tests_overall.tex
  - table_main_v2_pdr_noninferiority.tex
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import rankdata, wilcoxon


METRIC_SPECS = [
    {
        "metric": "att_share",
        "delta_col": "delta_att_share",
        "a_col": "a_att_share",
        "b_col": "b_att_share",
        "better": "lower",
    },
    {
        "metric": "hit_ratio",
        "delta_col": "delta_hit_ratio",
        "a_col": "a_hit_ratio",
        "b_col": "b_hit_ratio",
        "better": "lower",
    },
    {
        "metric": "churn",
        "delta_col": "delta_churn",
        "a_col": "a_churn",
        "b_col": "b_churn",
        "better": "lower",
    },
    {
        "metric": "pdr_dur",
        "delta_col": "delta_pdr_dur",
        "a_col": "a_pdr_dur",
        "b_col": "b_pdr_dur",
        "better": "higher",
    },
]


def fmt_p(x: float) -> str:
    if not np.isfinite(x):
        return "nan"
    if x < 1e-4:
        return "<1e-4"
    return f"{x:.4f}"


def holm_adjust(pvals: list[float]) -> list[float]:
    m = len(pvals)
    order = sorted(range(m), key=lambda i: pvals[i])
    adjusted_sorted = [0.0] * m
    running = 0.0
    for rank, idx in enumerate(order, start=1):
        raw = (m - rank + 1) * pvals[idx]
        running = max(running, raw)
        adjusted_sorted[rank - 1] = min(running, 1.0)

    out = [0.0] * m
    for rank, idx in enumerate(order, start=1):
        out[idx] = adjusted_sorted[rank - 1]
    return out


def cliffs_delta(a: np.ndarray, b: np.ndarray) -> float:
    gt = 0
    lt = 0
    for x in a:
        for y in b:
            if x > y:
                gt += 1
            elif x < y:
                lt += 1
    n = len(a) * len(b)
    if n == 0:
        return float("nan")
    return (gt - lt) / n


def rank_biserial_from_diffs(d: np.ndarray) -> float:
    nz = d[d != 0]
    if len(nz) == 0:
        return 0.0
    ranks = rankdata(np.abs(nz), method="average")
    w_plus = float(np.sum(ranks[nz > 0]))
    w_minus = float(np.sum(ranks[nz < 0]))
    denom = w_plus + w_minus
    if denom <= 0:
        return 0.0
    return (w_plus - w_minus) / denom


def signed_rank_pvalue(d: np.ndarray, better: str) -> tuple[float, float]:
    alt = "greater" if better == "higher" else "less"
    nz = d[d != 0]
    if len(nz) == 0:
        return 0.0, 1.0
    stat, p = wilcoxon(
        nz,
        alternative=alt,
        zero_method="wilcox",
        correction=False,
        mode="auto",
    )
    return float(stat), float(p)


def build_scope_frames(paired: pd.DataFrame) -> dict[str, pd.DataFrame]:
    scopes: dict[str, pd.DataFrame] = {"overall": paired.copy()}
    for d in sorted(paired["density"].unique()):
        scopes[str(d)] = paired[paired["density"] == d].copy()
    return scopes


def write_overall_tex(path: Path, rows: pd.DataFrame) -> None:
    lines = []
    lines.append("% Auto-generated by docs/paper/generate_main_stat_tests.py")
    lines.append("\\begin{table}[H]")
    lines.append("\\centering")
    lines.append("\\caption{Main v2 overall paired statistical tests (one-sided)}")
    lines.append("\\label{tab:main_v2_overall_paired_tests}")
    lines.append("\\begin{tabular}{lrrrrr}")
    lines.append("\\toprule")
    lines.append("Metric & Mean $\\Delta$ & Median $\\Delta$ & $p$ & Holm-$p$ & $r_{rb}$ (aligned) \\\\")
    lines.append("\\midrule")
    for _, r in rows.iterrows():
        metric_label = str(r["metric"]).replace("_", "\\_")
        lines.append(
            f"{metric_label} & "
            f"{r['mean_delta']:+.4f} & "
            f"{r['median_delta']:+.4f} & "
            f"{fmt_p(float(r['p_value']))} & "
            f"{fmt_p(float(r['p_value_holm']))} & "
            f"{float(r['rank_biserial_aligned']):+.3f} \\\\"
        )
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_noninferiority_tex(path: Path, rows: pd.DataFrame, margin: float) -> None:
    lines = []
    lines.append("% Auto-generated by docs/paper/generate_main_stat_tests.py")
    lines.append("\\begin{table}[H]")
    lines.append("\\centering")
    lines.append(
        "\\caption{PDR non-inferiority test by scope "
        f"(margin $\\Delta_{{NI}}={margin:+.2f}$, one-sided Wilcoxon)}}"
    )
    lines.append("\\label{tab:main_v2_pdr_noninferiority_test}")
    lines.append("\\begin{tabular}{lrrrr}")
    lines.append("\\toprule")
    lines.append("Scope & Mean $\\Delta$PDR & $p_{NI}$ & Holm-$p_{NI}$ & Decision \\\\")
    lines.append("\\midrule")
    for _, r in rows.iterrows():
        decision = "Pass" if bool(r["pass_holm_0_05"]) else "Fail"
        lines.append(
            f"{r['scope']} & "
            f"{float(r['mean_delta_pdr']):+.4f} & "
            f"{fmt_p(float(r['p_value_ni']))} & "
            f"{fmt_p(float(r['p_value_ni_holm']))} & "
            f"{decision} \\\\"
        )
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--paired-csv",
        type=Path,
        default=Path("docs/paper/generated/main_v2_final/paired_deltas_by_topology.csv"),
    )
    ap.add_argument(
        "--out-dir",
        type=Path,
        default=Path("docs/paper/generated/main_v2_final"),
    )
    ap.add_argument("--ni-margin", type=float, default=-0.02)
    args = ap.parse_args()

    paired = pd.read_csv(args.paired_csv)
    out_dir = args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    scopes = build_scope_frames(paired)
    rows: list[dict] = []
    for scope, g in scopes.items():
        for spec in METRIC_SPECS:
            d = g[spec["delta_col"]].to_numpy(dtype=float)
            a = g[spec["a_col"]].to_numpy(dtype=float)
            b = g[spec["b_col"]].to_numpy(dtype=float)

            stat, p = signed_rank_pvalue(d, spec["better"])
            rb = rank_biserial_from_diffs(d)
            cliff = cliffs_delta(a, b)

            aligned_rb = rb if spec["better"] == "higher" else -rb
            aligned_cliff = cliff if spec["better"] == "higher" else -cliff

            rows.append(
                {
                    "scope": scope,
                    "metric": spec["metric"],
                    "n": int(len(d)),
                    "mean_delta": float(np.mean(d)),
                    "median_delta": float(np.median(d)),
                    "wilcoxon_stat": stat,
                    "p_value": p,
                    "rank_biserial_raw": rb,
                    "rank_biserial_aligned": aligned_rb,
                    "cliffs_delta_raw": cliff,
                    "cliffs_delta_aligned": aligned_cliff,
                    "better_direction": spec["better"],
                }
            )

    stat_df = pd.DataFrame(rows)
    stat_df["p_value_holm"] = holm_adjust(stat_df["p_value"].tolist())
    stat_df["pass_holm_0_05"] = stat_df["p_value_holm"] < 0.05
    stat_df.to_csv(out_dir / "stat_tests_by_scope_metric.csv", index=False)

    # Non-inferiority: H0: delta_pdr <= margin, H1: delta_pdr > margin
    ni_rows: list[dict] = []
    for scope, g in scopes.items():
        d = g["delta_pdr_dur"].to_numpy(dtype=float)
        shifted = d - args.ni_margin
        stat, p = signed_rank_pvalue(shifted, "higher")
        rb = rank_biserial_from_diffs(shifted)
        ni_rows.append(
            {
                "scope": scope,
                "n": int(len(d)),
                "ni_margin": float(args.ni_margin),
                "mean_delta_pdr": float(np.mean(d)),
                "median_delta_pdr": float(np.median(d)),
                "median_shifted": float(np.median(shifted)),
                "wilcoxon_stat_ni": stat,
                "p_value_ni": p,
                "rank_biserial_ni": rb,
            }
        )

    ni_df = pd.DataFrame(ni_rows)
    ni_df["p_value_ni_holm"] = holm_adjust(ni_df["p_value_ni"].tolist())
    ni_df["pass_holm_0_05"] = ni_df["p_value_ni_holm"] < 0.05
    ni_df.to_csv(out_dir / "pdr_noninferiority_tests.csv", index=False)

    overall_rows = stat_df[stat_df["scope"] == "overall"].copy()
    order = ["att_share", "hit_ratio", "churn", "pdr_dur"]
    overall_rows["metric"] = pd.Categorical(overall_rows["metric"], order, ordered=True)
    overall_rows = overall_rows.sort_values("metric")
    write_overall_tex(out_dir / "table_main_v2_paired_tests_overall.tex", overall_rows)

    ni_order = ["overall", "sparse", "medium", "dense"]
    ni_rows_out = ni_df.copy()
    ni_rows_out["scope"] = pd.Categorical(ni_rows_out["scope"], ni_order, ordered=True)
    ni_rows_out = ni_rows_out.sort_values("scope")
    write_noninferiority_tex(
        out_dir / "table_main_v2_pdr_noninferiority.tex",
        ni_rows_out,
        args.ni_margin,
    )

    print("[OK] wrote:", out_dir / "stat_tests_by_scope_metric.csv")
    print("[OK] wrote:", out_dir / "pdr_noninferiority_tests.csv")
    print("[OK] wrote:", out_dir / "table_main_v2_paired_tests_overall.tex")
    print("[OK] wrote:", out_dir / "table_main_v2_pdr_noninferiority.tex")


if __name__ == "__main__":
    main()
