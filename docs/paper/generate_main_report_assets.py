def tex_escape(s: str) -> str:
    return (
        s.replace("\\", "\\textbackslash{}")
        .replace("&", "\\&")
        .replace("%", "\\%")
        .replace("$", "\\$")
        .replace("#", "\\#")
        .replace("_", "\\_")
        .replace("{", "\\{")
        .replace("}", "\\}")
    )


def read_csv(path: Path) -> List[dict]:
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def to_float(v: str) -> float:
    try:
        return float(v)
    except Exception:
        return float("nan")


def parse_defines(path: Path) -> Dict[str, str]:
    out: Dict[str, str] = {}
    if not path.exists():
        return out
    p = re.compile(r"^\s*#define\s+([A-Za-z_][A-Za-z0-9_]*)\s+(.+?)\s*$")
    for raw in path.read_text(encoding="utf-8").splitlines():
        m = p.match(raw)
        if not m:
            continue
        name, value = m.group(1), m.group(2)
        # strip inline comments
        value = value.split("/*", 1)[0].split("//", 1)[0].strip()
        out[name] = value
    return out


def parse_make_overrides(path: Path) -> Dict[str, str]:
    out: Dict[str, str] = {}
    if not path.exists():
        return out

    # CFLAGS += -DNAME=VALUE / CFLAGS += -DNAME
    rx = re.compile(r"-D([A-Za-z_][A-Za-z0-9_]*)(?:=([^\s\\]+))?")
    for line in path.read_text(encoding="utf-8").splitlines():
        for m in rx.finditer(line):
            name = m.group(1)
            val = m.group(2) if m.group(2) is not None else "1"
            out[name] = val
    return out


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


