def build_v13_tables() -> None:
    if not V1312_SUM.exists() or not V138_SUM.exists():
        return

    rows12 = read_csv(V1312_SUM)
    idx12 = {(r["topo"], r["proto"], r["scenario"]): r for r in rows12}
    rows8 = read_csv(V138_SUM)
    idx8 = {(r["topo"], r["proto"], r["scenario"]): r for r in rows8}

    cells = [("GRID", "SINK_ONLY"), ("GRID", "SINK_DROP50"), ("BOTTLE", "SINK_ONLY"), ("BOTTLE", "SINK_DROP50")]

    # cell table
    t1 = []
    t1.append("% Auto-generated by generate_main_report_assets.py")
    t1.append("\\begin{table*}[t]")
    t1.append("\\centering")
    t1.append("\\caption{v13.12(full40) 셀 단위 결과: BRPL vs TA-BRPL}")
    t1.append("\\label{tab:v13_full40_cells}")
    t1.append("\\begin{tabular}{llrrrrrrrrr}")
    t1.append("\\toprule")
    t1.append("Topo & Scenario & BRPL att & TA att & $\\Delta$att & BRPL hit & TA hit & $\\Delta$hit & BRPL churn & TA churn & $\\Delta$churn \\\\")
    t1.append("\\midrule")

    ds_att = []
    ds_hit = []
    ds_churn = []
    ds_pdr = []
    for topo, sc in cells:
        b = idx12[(topo, "BRPL", sc)]
        t = idx12[(topo, "TABRPL", sc)]
        datt = to_float(t["att_share"]) - to_float(b["att_share"])
        dhit = to_float(t["hit_ratio"]) - to_float(b["hit_ratio"])
        dchurn = to_float(t["churn"]) - to_float(b["churn"])
        dpdr = to_float(t["pdr_dur"]) - to_float(b["pdr_dur"])
        ds_att.append(datt)
        ds_hit.append(dhit)
        ds_churn.append(dchurn)
        ds_pdr.append(dpdr)

        t1.append(
            f"{topo} & {sc.replace('_','\\_')} & "
            f"{to_float(b['att_share']):.4f} & {to_float(t['att_share']):.4f} & {datt:+.4f} & "
            f"{to_float(b['hit_ratio']):.4f} & {to_float(t['hit_ratio']):.4f} & {dhit:+.4f} & "
            f"{to_float(b['churn']):.2f} & {to_float(t['churn']):.2f} & {dchurn:+.2f} \\\\")

    t1.append("\\midrule")
    t1.append(
        f"\\multicolumn{{2}}{{l}}{{Average}} & - & - & {sum(ds_att)/4:+.4f} & - & - & {sum(ds_hit)/4:+.4f} & - & - & {sum(ds_churn)/4:+.2f} \\\\"
    )
    t1.append("\\bottomrule")
    t1.append("\\end{tabular}")
    t1.append("\\end{table*}")
    write(OUT / "table_v13_full40_cells.tex", "\n".join(t1) + "\n")

    # v13.8 vs v13.12 compare
    def avg_delta(idx: Dict[Tuple[str, str, str], dict], metric: str) -> float:
        vals = []
        for topo, sc in cells:
            b = idx[(topo, "BRPL", sc)]
            t = idx[(topo, "TABRPL", sc)]
            vals.append(to_float(t[metric]) - to_float(b[metric]))
        return sum(vals) / len(vals)

    d8_att = avg_delta(idx8, "att_share")
    d8_hit = avg_delta(idx8, "hit_ratio")
    d8_churn = avg_delta(idx8, "churn")
    d8_pdr = avg_delta(idx8, "pdr_dur")

    d12_att = avg_delta(idx12, "att_share")
    d12_hit = avg_delta(idx12, "hit_ratio")
    d12_churn = avg_delta(idx12, "churn")
    d12_pdr = avg_delta(idx12, "pdr_dur")

    t2 = []
    t2.append("% Auto-generated by generate_main_report_assets.py")
    t2.append("\\begin{table}[t]")
    t2.append("\\centering")
    t2.append("\\caption{v13.8 대비 v13.12 평균 갭 비교 ($\\Delta$=TA-BRPL-BRPL)}")
    t2.append("\\label{tab:v13_version_compare}")
    t2.append("\\begin{tabular}{lrrrr}")
    t2.append("\\toprule")
    t2.append("Version & $\\Delta$att & $\\Delta$hit & $\\Delta$churn & $\\Delta$PDR \\\\")
    t2.append("\\midrule")
    t2.append(f"v13.8(full40) & {d8_att:+.4f} & {d8_hit:+.4f} & {d8_churn:+.2f} & {d8_pdr:+.4f} \\\\")
    t2.append(f"v13.12(full40) & {d12_att:+.4f} & {d12_hit:+.4f} & {d12_churn:+.2f} & {d12_pdr:+.4f} \\\\")
    t2.append("\\bottomrule")
    t2.append("\\end{tabular}")
    t2.append("\\end{table}")
    write(OUT / "table_v13_version_compare.tex", "\n".join(t2) + "\n")


