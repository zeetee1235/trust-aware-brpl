def build_figure_gallery() -> None:
    groups = [
        ("report", "Report Figures (auto-generated)", sorted((FIG_ROOT / "report").glob("*.pdf"))),
        ("new_main", "Main Experiment Figures", sorted((FIG_ROOT / "new" / "main").glob("*.pdf"))),
        ("new", "New Comparative Figures", sorted((FIG_ROOT / "new").glob("*.pdf"))),
        ("legacy", "Legacy Diagnostic Figures", sorted((FIG_ROOT / "legacy").glob("*.pdf"))),
    ]

    lines = []
    lines.append("% Auto-generated by generate_main_report_assets.py")
    inventory = []

    for key, title, files in groups:
        lines.append(f"\\section*{{{tex_escape(title)}}}")
        lines.append("\\addcontentsline{toc}{section}{" + tex_escape(title) + "}")
        inventory.append((title, len(files)))

        for p in files:
            rel = p.relative_to(FIG_ROOT).as_posix()
            stem = p.stem
            cap = f"{title}: {stem}"
            safe_label = re.sub(r"[^A-Za-z0-9:-]+", "-", f"fig-gallery-{key}-{stem}")
            lines.append("\\begin{figure}[p]")
            lines.append("  \\centering")
            lines.append(f"  \\includegraphics[width=0.96\\linewidth]{{{rel}}}")
            lines.append(f"  \\caption{{{tex_escape(cap)}}}")
            lines.append(f"  \\label{{{safe_label}}}")
            lines.append("\\end{figure}")
            lines.append("\\clearpage")

    write(OUT / "appendix_all_figures.tex", "\n".join(lines) + "\n")

    t = []
    t.append("% Auto-generated by generate_main_report_assets.py")
    t.append("\\begin{table}[t]")
    t.append("\\centering")
    t.append("\\caption{Figure inventory by source directory}")
    t.append("\\label{tab:figure_inventory}")
    t.append("\\begin{tabular}{lr}")
    t.append("\\toprule")
    t.append("Group & Count \\\\")
    t.append("\\midrule")
    total = 0
    for name, cnt in inventory:
        total += cnt
        t.append(f"{tex_escape(name)} & {cnt} \\\\")
    t.append("\\midrule")
    t.append(f"Total & {total} \\\\")
    t.append("\\bottomrule")
    t.append("\\end{tabular}")
    t.append("\\end{table}")
    write(OUT / "table_figure_inventory.tex", "\n".join(t) + "\n")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)

    defs = {}
    for p in [PROJECT_CONF, TRUST_C, BRPL_C]:
        defs.update(parse_defines(p))
    overrides = parse_make_overrides(MK_TABRPL)

    build_profile_table(overrides)
    model_param_table(defs, overrides)
    build_v13_tables()
    build_main_tables()
    build_figure_gallery()

    print(f"[OK] generated assets in {OUT}")


if __name__ == "__main__":
    main()
